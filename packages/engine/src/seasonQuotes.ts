const ROLE_LABEL: Record<SeasonQuoteRole, string> = {
  president: "Президент",
  sporting_director: "Спортивный директор",
  coach: "Главный тренер",
  captain: "Капитан",
};

function pickFresh(pool: string[], used: Set<string>, rng: Rng): string {
  const free = pool.filter((q) => !used.has(quoteFingerprint(q)));
  const chosen = free.length ? rng.pick(free) : rng.pick(pool);
  used.add(quoteFingerprint(chosen));
  return chosen;
}

export function buildSeasonEndQuotes(
  _pack: WorldPack,
  save: CareerSave,
  ctx: { place: number; userClubId: string; season: string }
): SeasonEndQuote[] {
  const tier = outcomeTier(ctx.place);
  const rng = new Rng(
    Array.from(`${save.id}:${ctx.season}:${ctx.place}:quotes`).reduce(
      (h, ch) => Math.imul(h ^ ch.charCodeAt(0), 16777619),
      2166136261
    ) >>> 0
  );
  const used = new Set<string>();
  const captain = pickCaptain(save, ctx.userClubId);

  const roles: SeasonQuoteRole[] = ["president", "sporting_director", "coach", "captain"];
  const pools: Record<SeasonQuoteRole, string[]> = {
    president: PRESIDENT[tier],
    sporting_director: SPORTING_DIRECTOR[tier],
    coach: COACH[tier],
    captain: CAPTAIN[tier],
  };

  return roles.map((role) => {
    const body = pickFresh(pools[role], used, rng);
    if (role === "captain") {
      const name = captain
        ? `${captain.firstName} ${captain.lastName}`
        : staffName("coach", ctx.userClubId);
      return {
        role,
        roleLabel: ROLE_LABEL[role],
        name,
        body,
        playerId: captain?.id,
        portraitId: captain?.portraitId,
      };
    }
    const nameRole = role === "coach" ? "coach" : role;
    return {
      role,
      roleLabel: ROLE_LABEL[role],
      name: staffName(nameRole, ctx.userClubId),
      body,
    };
  });
}
