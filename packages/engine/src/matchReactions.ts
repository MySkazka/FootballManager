function buildSide(
  clubId: string,
  gf: number,
  ga: number,
  stats: MatchSideStats,
  opp: MatchSideStats,
  events: MatchEvent[],
  isHome: boolean
): SideSnap {
  const story = analyzeSideStory(clubId, gf, ga, events);
  return {
    clubId,
    goalsFor: gf,
    goalsAgainst: ga,
    shots: stats.shots,
    shotsOn: stats.shotsOnTarget,
    oppShots: opp.shots,
    possession: possessionPct(stats, opp),
    yellows: stats.yellowCards,
    fouls: stats.fouls,
    outcome: outcome(gf, ga),
    isHome,
    ...story,
    reds: Math.max(stats.redCards, story.reds),
    oppReds: Math.max(opp.redCards, story.oppReds),
  };
}

/** Post-match quotes: one player per side + both coaches, based on match story. */
export function buildMatchReactions(
  result: MatchResult,
  players: Player[],
  homeClubId: string,
  awayClubId: string,
  homeStats: MatchSideStats,
  awayStats: MatchSideStats,
  seed = 1
): MatchReaction[] {
  const rng = new Rng(seed >>> 0 || 1);
  const bag: QuoteBag = { used: new Set(), rng };
  const ratings = result.ratings ?? {};
  const homeLine = result.homeLineup ?? [];
  const awayLine = result.awayLineup ?? [];
  const events = result.events ?? [];

  const homeSide = buildSide(
    homeClubId,
    result.homeGoals,
    result.awayGoals,
    homeStats,
    awayStats,
    events,
    true
  );
  const awaySide = buildSide(
    awayClubId,
    result.awayGoals,
    result.homeGoals,
    awayStats,
    homeStats,
    events,
    false
  );

  const reactions: MatchReaction[] = [];

  const addPlayer = (side: SideSnap, lineup: string[]) => {
    const p = pickSidePlayer(side.clubId, lineup, players, ratings, result, rng);
    if (!p) return;
    const goalsScored = events.filter((e) => e.type === "goal" && e.playerId === p.id).length;
    const yellow = events.some(
      (e) => e.type === "card" && e.detail !== "red" && e.playerId === p.id
    );
    const red = events.some((e) => e.type === "card" && e.detail === "red" && e.playerId === p.id);
    reactions.push({
      role: "player",
      name: playerDisplayName(p),
      clubId: side.clubId,
      playerId: p.id,
      quote: playerQuote(side, ratings[p.id] ?? 6.5, goalsScored, yellow, red, bag),
    });
  };

  addPlayer(homeSide, homeLine);
  addPlayer(awaySide, awayLine);

  reactions.push({
    role: "coach",
    name: coachNameForClub(homeClubId),
    clubId: homeClubId,
    quote: coachQuote(homeSide, bag),
  });
  reactions.push({
    role: "coach",
    name: coachNameForClub(awayClubId),
    clubId: awayClubId,
    quote: coachQuote(awaySide, bag),
  });

  return reactions;
}

export function reactionSeedFromResult(result: MatchResult, homeClubId: string, awayClubId: string): number {
  let h = 2166136261;
  const raw = `${homeClubId}|${awayClubId}|${result.homeGoals}:${result.awayGoals}|${result.events.length}|${result.homeShots}:${result.awayShots}`;
  for (let i = 0; i < raw.length; i++) {
    h ^= raw.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  for (const e of result.events.slice(0, 12)) {
    h ^= e.minute + (e.playerId?.length ?? 0) * 17;
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
