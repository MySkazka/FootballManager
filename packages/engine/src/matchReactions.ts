  const wasteful = side.shotsOn >= 4 && side.goalsFor === 0;
  const clinical = side.goalsFor >= 2 && side.shotsOn > 0 && side.goalsFor >= side.shotsOn - 1;
  const dominated = side.possession >= 60 && side.shots >= side.oppShots + 2;
  const underSiege = side.oppShots >= side.shots + 4;
  const dirty = side.yellows + side.reds * 2 >= 3;
  const men = menLabel(side.reds);
  const venue = side.isHome ? "дома" : "в гостях";

  if (side.reds >= 1 && side.outcome === "draw") {
    if (side.earlyReds >= 2 || side.reds >= 2) {
      return pickFresh(
        [
          `Два удаления в начале — и всё равно очко ${venue}. Характер у команды железный, а вот мозги в штрафной сегодня отдыхали. Дисциплину разберём жёстко: такие «подарки» сезон не прощает. Но за стойкость ${men} — отдельное спасибо раздевалке.`,
          `Спаслись ${men}, и это звучит как подвиг, потому что так оно и было. Карточки в дебюте могли похоронить всё — вместо этого вырвали ничью. Я зол на самоубийства и горжусь, что никто не сломался. Завтра видеоразбор будет без скидок.`,
          `Играть ${men} после ранних красных — это уже не тактика, а выживание. Очко забираем, эмоции смешанные: уважение к характеру и претензии к нервам. В футболе глупость наказывается быстрее, чем слабость. Сегодня наказали себя сами — и всё равно устояли.`,
        ],
        bag
      );
    }
    if (side.earlyReds >= 1 || (side.firstRedMinute != null && side.firstRedMinute <= 30)) {
      return pickFresh(
        [
          `Удаление рано перевернуло план, а ребята всё равно вытащили очко ${venue}. Это уже не про схему — про характер. Конечно, без красной жили бы спокойнее и, возможно, брали бы три. Но сегодня я заберу ничью как маленькую победу у хаоса.`,
          `Играли ${men} большую часть матча и не развалились — редкость. План пришлось рвать на клочки прямо с бровки. Очко есть, претензий к дисциплине — вагон. Завтра скажу прямо: геройство не отменяет тупых удалений.`,
        ],
        bag
      );
    }
    return pickFresh(
      [
        `Удержание ${men} — уже подвиг, ничья ${venue} сегодня как медаль. Да, хотелось большего, но реалисты знают цену такому очку. Дисциплину всё равно поднимем на щит. Красиво не было — зато было по-мужски.`,
        `Меньшинство не сломало команду, и это главное. Мы гнули спину, закрывали зоны и всё-таки ушли с очком. Я не буду делать вид, что доволен карточками. Но характер вижу — с таким характером можно пройти сезон.`,
      ],
      bag
    );
  }

  if (side.reds >= 1 && side.outcome === "win") {
    return pickFresh(
      [
        `Победа ${men} — заявка на характер, без прикрас. Без удаления было бы проще, спорить бессмысленно. Но раз уж сами себе устроили квест, то прошли его на три очка. Дисциплину всё равно подниму — геройство не должно становиться привычкой.`,
        `Выиграли несмотря на удаление, и раздевалка сейчас орёт от счастья — правильно орёт. Я чуть спокойнее: такие матчи закаляют, но и учат дорогой ценой. Три очка наши. Завтра разберём, как не дарить сопернику фору.`,
      ],
      bag
    );
  }

  if (side.reds >= 1 && side.outcome === "loss") {
    return pickFresh(
      [
        `Раннее удаление похоронило матч, и это надо признать без театра. Нельзя дарить сопернику такую фору и потом удивляться счёту. Да, в меньшинстве тяжело — но до карточки уже играли нервно. Разберём и исправим, иначе такие вечера будут повторяться.`,
        `Удаление развалило структуру, а с ней и шансы. Поражение во многом сами себе устроили — горько, но честно. В раздевалке тихо, и это правильно. Завтра без жалости к ошибкам: сезон не ждёт понедельничных оправданий.`,
      ],
      bag
    );
  }

  if (side.oppReds >= 1 && side.outcome === "draw") {
    if (side.earlyOppReds >= 2 || side.oppReds >= 2) {
      return pickFresh(
        [
          `Играли против девяти почти весь матч — и отпустили ничью. Это нельзя прощать, точка. Моментов хватало, чтобы закрыть вопрос до перерыва. Вместо этого позволили сопернику поверить в чудо. Завтра на разборе будет громко.`,
          `Численное большинство было огромным, а очко одно — математика стыдная. Должны были добивать, а не кататься в полтемпа. Соперник выжил за счёт характера, мы потеряли очки за счёт расслабленности. Такие матчи сезон помнит долго.`,
        ],
        bag
      );
    }
    return pickFresh(
      [
        `Соперник остался в меньшинстве, а мы не воспользовались — обидная ничья ${venue}. Большинство надо реализовывать холодно, без суеты и без жалости. Сегодня жалости к себе было слишком много. Очко есть, удовлетворения нет.`,
        `Имели численное преимущество и ушли с ничьей. Мало агрессии в завершении, много разговоров в середине поля. Такие игры нужно убивать рано. Завтра скажу команде прямо: фора — не подарок, а обязанность.`,
      ],
      bag
    );
  }

  if (side.oppReds >= 1 && side.outcome === "loss") {
    return pickFresh(
      [
        `Даже большинство не спасло — слишком мягко в ключевые моменты. Соперник играл в меньшинстве и всё равно нас наказал. Это уже не про удачу, это про характер. Жёсткий урок, который нельзя проспать.`,
        `Имели фору и всё равно проиграли — редкий вид спортивного самоубийства. Моменты были, реализации нет, спокойствия ещё меньше. Разберём без анестезии. Такие вечера не забываются сами собой.`,
      ],
      bag
    );
  }

  if (side.oppReds >= 1 && side.outcome === "win") {
    return pickFresh(
      [
        `Воспользовались удалением соперника и дожали — правильно. Не надо извиняться за профессионализм. Спокойно контролировали, не дали им поверить в сказку. Три очка ${venue} — идём дальше без эйфории.`,
        `Численное преимущество реализовали без истерики. Иногда футбол любит простых решений: давление, терпение, гол. Сегодня так и вышло. Доволен, но напоминаю: без красной у них тоже надо уметь побеждать.`,
      ],
      bag
    );
  }

  if (side.lateEqualizer && side.outcome === "draw") {
    return pickFresh(
      [
        `Спаслись в концовке — очко вырвали зубами. До этого момента матч ускользал, нервы пели. Рад, что не опустили руки, когда проще было сдаться. Такие ничьи потом вспоминаешь теплее иных побед.`,
        `Поздний гол стоит дорого, особенно ${venue}. Ребята не согласились с сценарием и переписали его в последней главе. Очко заслужено характером. Завтра похвалим стойкость — и всё равно разберём, почему так затянули.`,
      ],
      bag
    );
  }

  if (side.lateWinner && side.outcome === "win") {
    return pickFresh(
      [
        `Решили всё в концовке — холодная голова в такие минуты на вес золота. Долго давили, не паниковали, дождались своего. Три очка ${venue} после такого финала особенно сладкие. Пусть соперник привыкает: мы умеем добивать.`,
        `Поздний гол — награда за терпение, не за удачу. Мы верили до последней подачи, и поле это почувствовало. Раздевалка сейчас гудит, и пусть гудит. Сезон любит команды, которые не смотрят на часы раньше времени.`,
      ],
      bag
    );
  }

  if (side.comeback && side.outcome === "win") {
    return pickFresh(
      [
        `Отстали и всё равно выиграли — это уже характер, а не случайность. Важно, что никто не спрятался после пропущенного. Перестроились, добавили злости и забрали своё. Такие победы склеивают раздевалку лучше любых речей.`,
        `Камбэк сегодня говорит о характере не меньше, чем о тактике. Было тяжело, было шумно, было по делу. Три очка вырвали, а не получили в подарок. Завтра продолжим в том же тоне — без жалости к себе.`,
      ],
      bag
    );
  }

  if (side.outcome === "win") {
    if (clinical) {
      return pickFresh(
        [
          `Реализовали моменты — в этом и была вся разница. Не надо сто ударов, нужны два точных. Сегодня сыграли по-взрослому: терпеливо и жёстко в завершении. Три очка ${venue} — продолжаем.`,
          `Две-три атаки решили матч, и это комплимент холодной голове. Контролировали темп, не лезли в хаос. Победа без лишней драмы — мой любимый жанр. Идём дальше без эйфории.`,
        ],
        bag
      );
    }
    if (dominated) {
      return pickFresh(
        [
          `Контролировали игру почти весь матч и закономерно взяли своё. Владение без остроты было бы пустым — сегодня остроты хватило. Соперник устал раньше нас, это видно. Правильная победа ${venue}.`,
          `Давили, держали мяч и не отпускали нить игры. Иногда красиво, иногда грязно — главное, эффективно. Три очка заслужили по содержанию. Завтра тот же стандарт, без скидок.`,
        ],
        bag
      );
    }
    if (margin === 1) {
      return pickFresh(
        [
          `Тяжёлая, но важная победа. Не всегда бывает красиво — иногда бывает нужно. Ребята вытерпели, и это дорогого стоит. Три очка в копилку, характер в плюс.`,
          `Минимальная победа — тоже три очка, кто забыл. Нервы поиграли, ноги поработали, голова выдержала. Я доволен результатом больше, чем картинкой. Сезон длинный, такие вечера решают.`,
        ],
        bag
      );
    }
    if (dirty) {
      return pickFresh(
        [
          `Победа есть, а вот дисциплина хромала — разберём жёлтые отдельно. Не надо путать дерзость с глупостью. Результат радует, эмоции смешанные. Завтра напомним: спокойствие тоже часть тактики.`,
          `Взяли три очка, но слишком часто играли на грани фола. Мне нравится злость, не нравится хаос. Победа не отменяет претензий. Исправим до того, как судья исправит за нас.`,
        ],
        bag
      );
    }
    return pickFresh(
      [
        `Ребята выложились и получили то, чего заслужили. Без лишней поэзии: работали, терпели, дожали. Раздевалка довольна — я тоже. Сезон длинный, продолжаем в том же духе.`,
        `Хорошая командная работа ${venue}: от первого паса до последнего отбора. Победа выглядит заслуженной, и это приятно. Не расслабляемся. Завтра уже думаем о следующем сопернике.`,
      ],
      bag
    );
  }

